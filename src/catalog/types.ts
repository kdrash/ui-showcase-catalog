export interface DemoEntry {
  /** unique kebab-case id */
  id: string
  /** 表示名 */
  title: string
  /** 何をしているUIか(日本語 1〜2文) */
  description: string
  category: CategoryId
  styles: StyleId[]
  tech: TechId[]
  /** 今後のプロジェクトでこのUIを依頼するときのプロンプト例(日本語) */
  prompt: string
  /** src/demos からの相対パス。コード表示に使う (例: 'cards/TiltCard.tsx') */
  file: string
  component: ComponentType
  /** プレビュー高さ(px)。デフォルト 320 */
  height?: number
  /** グリッドで2カラム分の幅を使う */
  wide?: boolean
  /** WebGL等の重いデモ。画面外でアンマウントする */
  heavy?: boolean
  /** カタログに追加した日(YYYY-MM-DD)。一定期間「NEW」と表示し、新着順の並び替えに使う */
  added?: string
}
